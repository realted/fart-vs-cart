; ============================================
; 16-bit vector datapath test
;
; Expected final memory:
;
; addr 72 = 0x0100    ; 255 + 1   = 256
; addr 73 = 0x0101    ; 255 + 2   = 257
; addr 74 = 0x0100    ; 128 + 128 = 256
; addr 75 = 0x012C    ; 200 + 100 = 300
; ============================================


; --------------------------------------------
; Load X0 from addresses 64-67
; --------------------------------------------

    ori     16          ; k1 = 16
    nop
    nop
    nop

    shiftl  k1,2        ; k1 = 16 << 2 = 64
    nop
    nop
    nop

    vload   v0,(k1)     ; X0 = MEM[64:67]
    nop
    nop
    nop


; --------------------------------------------
; Change base address from 64 -> 68
;
; 64 = 0b01000000
; OR 4 = 0b01000100 = 68
; --------------------------------------------

    ori     4           ; k1 = 68
    nop
    nop
    nop

    vload   v1,(k1)     ; X1 = MEM[68:71]
    nop
    nop
    nop


; --------------------------------------------
; Perform 16-bit vector addition
; --------------------------------------------

    vadd    v0,v1
    nop
    nop
    nop


; --------------------------------------------
; Create address 72
; 18 << 2 = 72
; --------------------------------------------

    sub     k1,k1       ; k1 = 0
    nop
    nop
    nop

    ori     18          ; k1 = 18
    nop
    nop
    nop

    shiftl  k1,2        ; k1 = 72
    nop
    nop
    nop


; --------------------------------------------
; Write result to addresses 72-75
; --------------------------------------------

    vstore  v0,(k1)
    nop
    nop
    nop

    stop


; ============================================
; Input vectors
; ============================================

    org 64
a0      db 255
a1      db 255
a2      db 128
a3      db 200

    org 68
b0      db 1
b1      db 2
b2      db 128
b3      db 100
